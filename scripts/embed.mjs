// Bundles config.example.json and the extension files into src/embedded.js so the
// packaged executable can recreate them on first run. Re-run after editing them.
import fs from 'node:fs';
const files = ['config.example.json', 'extension/manifest.json', 'extension/background.js', 'extension/popup.html', 'extension/popup.js'];
const out = Object.fromEntries(files.map((f) => [f, fs.readFileSync(new URL(`../${f}`, import.meta.url), 'utf8')]));
fs.writeFileSync(new URL('../src/embedded.js', import.meta.url),
  `// GENERATED by scripts/embed.mjs — do not edit.\nexport default ${JSON.stringify(out, null, 0)};\n`);
console.log(`embedded ${files.length} files`);
